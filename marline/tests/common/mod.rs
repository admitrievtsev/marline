//! Deterministic dataset generator for end-to-end tests.
//!
//! The corpus is built from a fixed seed: the same seed always yields the same
//! bytes. It covers the data classes relevant to deduplication / delta
//! compression: exact duplicates, near-duplicates (versions with edits),
//! unrelated documents, and boundary sizes. Pipeline-agnostic: works for both
//! SBC and Palantir.

/// Corpus options.
///
/// Fields are private so the generator invariants (non-zero sizes, a bounded
/// mutation fraction) cannot be broken after construction; build a validated
/// instance with [`Options::new`].
#[derive(Clone, PartialEq)]
pub struct Options {
    /// Number of logical documents (groups of similar content).
    docs: usize,
    /// Versions per group, including the base.
    versions: usize,
    /// Base document size in bytes.
    size: usize,
    /// Fraction of bytes edited in versions (0.0..=1.0).
    mutate_fraction: f64,
    /// Whether to include boundary sizes (empty, 1 byte, ~16K/32K).
    edge_cases: bool,
}

impl Options {
    /// Builds validated options.
    ///
    /// # Panics
    ///
    /// Panics if `docs` or `versions` is zero, if `size` is zero, or if
    /// `mutate_fraction` is not a finite value in `0.0..=1.0`.
    pub fn new(
        docs: usize,
        versions: usize,
        size: usize,
        mutate_fraction: f64,
        edge_cases: bool,
    ) -> Self {
        assert!(docs > 0, "docs must be > 0");
        assert!(versions > 0, "versions must be > 0");
        assert!(size > 0, "size must be > 0");
        assert!(
            mutate_fraction.is_finite() && (0.0..=1.0).contains(&mutate_fraction),
            "mutate_fraction must be finite and within 0.0..=1.0"
        );
        Self { docs, versions, size, mutate_fraction, edge_cases }
    }
}

impl Default for Options {
    fn default() -> Self {
        Self::new(4, 4, 256 * 1024, 0.03, true)
    }
}

/// A ready-to-use corpus.
///
/// Fields are private; the document classes are exposed through the accessor
/// methods below.
#[derive(Clone, PartialEq)]
pub struct Corpus {
    /// Groups of similar documents: the first element is the base, the rest are versions.
    similar_groups: Vec<Vec<Vec<u8>>>,
    /// Unrelated documents (must not form pairs).
    unrelated: Vec<Vec<u8>>,
    /// Boundary sizes.
    edge_cases: Vec<Vec<u8>>,
}

impl Corpus {
    /// Groups of similar documents: the first element is the base, the rest
    /// are versions.
    pub fn similar_groups(&self) -> &[Vec<Vec<u8>>] {
        &self.similar_groups
    }

    /// Unrelated documents (must not form pairs).
    pub fn unrelated(&self) -> &[Vec<u8>] {
        &self.unrelated
    }

    /// Boundary-size documents.
    pub fn edge_cases(&self) -> &[Vec<u8>] {
        &self.edge_cases
    }

    /// Total size of all documents.
    pub fn total_bytes(&self) -> usize {
        self.similar_groups
            .iter()
            .flatten()
            .chain(&self.unrelated)
            .chain(&self.edge_cases)
            .map(Vec::len)
            .sum()
    }

    /// All documents flattened (order is stable for a given seed).
    pub fn all(&self) -> Vec<&[u8]> {
        self.similar_groups
            .iter()
            .flatten()
            .chain(&self.unrelated)
            .chain(&self.edge_cases)
            .map(Vec::as_slice)
            .collect()
    }
}

/// 64-bit fractional part of the golden ratio; splitmix64's state increment.
///
/// `GOLDEN_RATIO_64` and the two `MIX_MULTIPLIER` constants are the standard
/// splitmix64 constants from the algorithm's specification, not values chosen
/// by us. They are fixed for reproducibility: changing them would silently
/// change every generated byte stream.
const GOLDEN_RATIO_64: u64 = 0x9E37_79B9_7F4A_7C15;

/// Splitmix64 mixing multipliers.
const MIX_MULTIPLIER_1: u64 = 0xBF58_476D_1CE4_E5B9;
const MIX_MULTIPLIER_2: u64 = 0x94D0_49BB_1331_11EB;

/// Seed salts separating the PRNG streams of the corpus classes (versions,
/// unrelated documents, edge cases) from each other and from the base seed.
///
/// `SALT_VERSION` gives every version of a document a seed distinct from its
/// base: multiplying the version number by an odd constant is bijective
/// modulo 2^64, so different versions never collide. The concrete values are
/// arbitrary but fixed — any distinct, non-zero constants would do. The
/// original values are kept so the generated bytes stay identical to the
/// committed generator.
const SALT_VERSION: u64 = GOLDEN_RATIO_64;
const SALT_UNRELATED: u64 = 0xDEAD_BEEF;
const SALT_EDGE: u64 = 0x1234_5678;

/// Multiplier for unrelated-document seeds.
///
/// Deliberately the 32-bit constant `0x9E37_79B9` (the *upper* 32 bits of
/// the golden ratio), not the full 64-bit `GOLDEN_RATIO_64`. Multiplying by
/// the full constant silently degrades the streams, making documents i=0 and
/// i=3 near-identical — that broke the
/// `unrelated_documents_are_stored_raw_and_roundtrip` test. Keep this value.
const UNRELATED_SEED_MULTIPLIER: u64 = 0x9E37_79B9;

/// Face-case block size and repeated byte used for the constant 64 KiB chunk.
const EDGE_16K: usize = 16 * 1024;
const EDGE_32K: usize = 32 * 1024;
const EDGE_64K: usize = 64 * 1024;
const REPEATED_BYTE: u8 = 0xAB;

struct Rng {
    state: u64,
}

impl Rng {
    fn new(seed: u64) -> Self {
        Self { state: seed }
    }

    fn next_u64(&mut self) -> u64 {
        self.state = self.state.wrapping_add(GOLDEN_RATIO_64);
        let mut z = self.state;
        z = (z ^ (z >> 30)).wrapping_mul(MIX_MULTIPLIER_1);
        z = (z ^ (z >> 27)).wrapping_mul(MIX_MULTIPLIER_2);
        z ^ (z >> 31)
    }

    fn next_usize(&mut self, n: usize) -> usize {
        if n == 0 {
            0
        } else {
            (self.next_u64() % n as u64) as usize
        }
    }

    fn bytes(&mut self, len: usize) -> Vec<u8> {
        let mut v = Vec::with_capacity(len);
        while v.len() < len {
            for b in self.next_u64().to_le_bytes() {
                if v.len() < len {
                    v.push(b);
                }
            }
        }
        v
    }
}

/// Builds a corpus from a seed.
pub fn build(seed: u64, opts: &Options) -> Corpus {
    let mut base_rng = Rng::new(seed);

    let similar_groups = (0..opts.docs)
        .map(|doc| {
            let base = base_rng.bytes(opts.size);
            let mut group = Vec::with_capacity(opts.versions);
            group.push(base.clone());
            for version in 1..opts.versions {
                let version_seed =
                    seed ^ ((doc as u64 + 1) << 32) ^ (version as u64).wrapping_mul(SALT_VERSION);
                group.push(mutate(&base, version_seed, opts.mutate_fraction));
            }
            group
        })
        .collect();

    let unrelated = (0..opts.docs)
        .map(|i| {
            let mut rng = Rng::new(
                seed ^ (SALT_UNRELATED + i as u64).wrapping_mul(UNRELATED_SEED_MULTIPLIER),
            );
            rng.bytes(opts.size / 2 + i)
        })
        .collect();

    let edge_cases = if opts.edge_cases {
        let mut rng = Rng::new(seed ^ SALT_EDGE);
        vec![
            Vec::new(),
            vec![0u8],
            rng.bytes(EDGE_16K),
            rng.bytes(EDGE_32K + 1),
            vec![REPEATED_BYTE; EDGE_64K],
        ]
    } else {
        Vec::new()
    };

    Corpus { similar_groups, unrelated, edge_cases }
}

/// Prints a small aligned key/value block under a title.
pub fn report(title: &str, rows: &[(&str, String)]) {
    eprintln!("==== {title} ====");
    for (label, value) in rows {
        eprintln!("  {label:<22} {value}");
    }
    eprintln!("--------------------");
}

/// Formats a byte count with space-separated digit groups for readability.
pub fn fmt_size(n: usize) -> String {
    let s = n.to_string();
    let mut out = String::new();
    for (i, ch) in s.chars().rev().enumerate() {
        if i > 0 && i % 3 == 0 {
            out.push(' ');
        }
        out.push(ch);
    }
    out.chars().rev().collect()
}

/// Applies deterministic edits (replace/insert/delete) to the base.
///
/// Edits are confined to a randomly placed contiguous window covering a small
/// fraction of the document, like real near-duplicates (a few changed
/// regions). Scattering edits across the whole document would perturb every
/// rolling-hash mark and defeat similarity hashing entirely.
///
/// * `base` — the source document to edit.
/// * `seed` — deterministically drives both the window position and every edit.
/// * `fraction` — how large a share of the window (in bytes) gets modified.
fn mutate(base: &[u8], seed: u64, fraction: f64) -> Vec<u8> {
    let mut out = base.to_vec();
    if out.is_empty() {
        return out;
    }

    let mut rng = Rng::new(seed);
    let window_len = (base.len() / 16).max(64).min(base.len());
    let window_start = rng.next_usize(base.len() - window_len + 1);
    let window_end = window_start + window_len;
    let edits = ((window_len as f64 * fraction) as usize).clamp(1, window_len);

    for _ in 0..edits {
        let idx_in_window = rng.next_usize(window_len);
        let idx = window_start + idx_in_window;
        match rng.next_usize(3) {
            0 => {
                let n = 1 + rng.next_usize(4).min(window_end - idx);
                for b in out.iter_mut().skip(idx).take(n) {
                    *b = (rng.next_u64() & 0xff) as u8;
                }
            }
            1 => {
                let insert_idx = rng.next_usize(window_len + 1);
                let block_len = 1 + rng.next_usize(16);
                let block = rng.bytes(block_len);
                out.splice(window_start + insert_idx..window_start + insert_idx, block);
            }
            _ => {
                if window_end - idx > 1 {
                    let n = 1 + rng.next_usize(8).min(window_end - idx - 1);
                    out.drain(idx..idx + n);
                }
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn corpus_is_deterministic() {
        let a = build(7, &Options::default());
        let b = build(7, &Options::default());
        assert!(a == b);
    }

    #[test]
    fn corpus_differs_by_seed() {
        assert!(build(7, &Options::default()) != build(8, &Options::default()));
    }

    #[test]
    fn corpus_has_all_classes() {
        let c = build(7, &Options::default());
        assert!(!c.similar_groups().is_empty());
        assert!(!c.unrelated().is_empty());
        assert!(!c.edge_cases().is_empty());
        assert!(c.total_bytes() > 0);
        let group = &c.similar_groups()[0];
        assert!(group.len() >= 2);
        assert!(group[0] != group[1], "a version must differ from its base");
    }

    #[test]
    fn mutate_keeps_length_bounded() {
        let base = Rng::new(1).bytes(64 * 1024);
        let version = mutate(&base, 99, 0.01);
        let ratio = version.len() as f64 / base.len() as f64;
        assert!((ratio - 1.0).abs() < 0.1, "length must not drift far: {ratio}");
    }
}
